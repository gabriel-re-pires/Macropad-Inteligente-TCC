FONT: bytes = bytes.fromhex(_FONT_HEX)
if len(FONT) != 256 * GLYPH_W:  # pragma: no cover — tabela embutida
    raise RuntimeError("tabela da fonte 5x7 corrompida")


def glyph(code: int) -> bytes:
    """Cinco bytes-coluna do caractere ``code`` (0..255)."""
    code &= 0xFF
    return FONT[code * GLYPH_W : (code + 1) * GLYPH_W]
